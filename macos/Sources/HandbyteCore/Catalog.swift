    private static func preset(
        id: String,
        path: String,
        expandChildren: Bool = false,
        category: Category,
        safety: Safety,
        owners: [String] = [],
        summary: String,
        recovery: String
    ) -> Rule {
        Rule(
            id: id,
            kind: .preset(pathTemplate: path, expandChildren: expandChildren),
            category: category,
            safety: safety,
            ownerBundleIDs: owners,
            summary: summary,
            recovery: recovery
        )
    }

    private static func artifact(
        name: String,
        safety: Safety,
        summary: String,
        recovery: String
    ) -> Rule {
        Rule(
            id: "artifact:\(name)",
            kind: .projectArtifact(directoryName: name),
            category: .projectBuild,
            safety: safety,
            ownerBundleIDs: [],
            summary: summary,
            recovery: recovery
        )
    }
